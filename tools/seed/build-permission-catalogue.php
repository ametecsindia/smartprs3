<?php
/**
 * Generates src/Platform/Access/catalogue.php from the blueprint's generated
 * permission register.
 *
 *   php tools/seed/build-permission-catalogue.php [path/to/REGISTER-PERMISSIONS.md]
 *
 * The register (docs/registers/REGISTER-PERMISSIONS.md) is itself generated from
 * the parts by tools/generate-registers.py, so this is a second-order generator:
 * the parts are the source of truth, and neither the register nor catalogue.php
 * is ever hand-edited.
 *
 * Two skip rules, both from Part XXII §XXII.2:
 *
 *   1. R-XXII-010a — the reserved generative namespaces `form.*`, `report.*` and
 *      `dashboard.*` are minted by the platform from published artefact versions.
 *      "A migration MUST NOT insert a row in a reserved namespace, and the
 *      catalogue validator MUST reject one that appears." A seeded declared entry
 *      IS that row, so every code in those namespaces is skipped and reported.
 *   2. The grammar of §XXII.2.1 — anything Permission::of() will not construct is
 *      skipped rather than seeded, because an unconstructable code is a code no
 *      route can ever bind to.
 *
 * Output columns: code => [module, introduced-by parts, catalogue group].
 */
declare(strict_types=1);

require_once __DIR__ . '/../../src/Platform/Access/Permission.php';

use SmartPRS\Platform\Access\Permission;

const RESERVED = ['form', 'report', 'dashboard'];

$register = $argv[1] ?? dirname(__DIR__, 3) . '/blueprint/docs/registers/REGISTER-PERMISSIONS.md';
$out = dirname(__DIR__, 2) . '/src/Platform/Access/catalogue.php';

$md = @file_get_contents($register);
if ($md === false) {
    fwrite(STDERR, "cannot read register: $register\n");
    exit(2);
}

// Section 3 is the full register: | `code` | Catalogued | Catalogue group | Used by |
$section = null;
if (preg_match('/^## 3\. The full register\s*$(.*?)^## 4\./ms', $md, $m)) {
    $section = $m[1];
}
if ($section === null) {
    fwrite(STDERR, "register has no '## 3. The full register' section\n");
    exit(2);
}

$seeded = [];
$skipped = [];
$rows = 0;

foreach (explode("\n", $section) as $line) {
    if (!preg_match('/^\|\s*`([^`]+)`\s*\|([^|]*)\|([^|]*)\|([^|]*)\|/', $line, $m)) {
        continue;
    }
    $rows++;
    $code = trim($m[1]);
    $group = trim(str_replace('—', '', $m[3]));
    $parts = trim($m[4]);

    try {
        $permission = Permission::of($code);
    } catch (Throwable $e) {
        $skipped[] = [$code, 'malformed under §XXII.2.1: ' . $e->getMessage()];
        continue;
    }

    if (in_array($permission->module(), RESERVED, true)) {
        $skipped[] = [$code, 'reserved generative namespace `' . $permission->module() . '.*` (R-XXII-010a)'];
        continue;
    }

    $seeded[$code] = [$permission->module(), $parts, $group];
}

ksort($seeded);

$php = <<<'HEAD'
<?php

/**
 * THE AMETECS-AUTHORED PERMISSION CATALOGUE — GENERATED, DO NOT HAND-EDIT.
 *
 * Generated by tools/seed/build-permission-catalogue.php from the blueprint's
 * docs/registers/REGISTER-PERMISSIONS.md, which is itself generated from the
 * parts. Change a part, regenerate the register, regenerate this file.
 *
 * This is path A of R-XXII-010: an Ametecs-authored entry, shipped in a release.
 * Path B — the reserved generative namespaces form.*, report.* and dashboard.* —
 * is NOT here and must not be: those codes are minted by the platform from a
 * published artefact version (R-XXII-010a), and PermissionCatalogue rejects this
 * file outright if one appears in it.
 *
 * Columns: code => [module, parts that declare an operation on it, §XXII.2.2
 * catalogue group ('' where the code is used by a part but §XXII.2.2 does not
 * yet carry a row — the visible work queue R-XXII-010b describes)].
 */

declare(strict_types=1);

return [

HEAD;

foreach ($seeded as $code => [$module, $parts, $group]) {
    $php .= sprintf(
        "    %-44s => [%-18s %-14s %s],\n",
        var_export($code, true),
        var_export($module, true) . ',',
        var_export($parts, true) . ',',
        var_export($group, true),
    );
}

$php .= "];\n";

file_put_contents($out, $php);

printf("register rows      %d\n", $rows);
printf("seeded             %d  -> %s\n", count($seeded), $out);
printf("skipped            %d\n", count($skipped));

$byReason = [];
foreach ($skipped as [$code, $reason]) {
    $byReason[$reason][] = $code;
}
foreach ($byReason as $reason => $codes) {
    printf("  %s\n", $reason);
    foreach ($codes as $c) {
        printf("    %s\n", $c);
    }
}
