<?php
/**
 * THE GRANTS THE db-privilege GATE ASKS FOR — Law 2, Part IV §IV.10.
 *
 *   php tools/db/grants.php [database] [account] [host]
 *
 * The gate says what the application account must NOT hold. Nothing said what
 * it SHOULD hold, and the first attempt at satisfying it from memory failed for
 * a reason worth writing down once rather than rediscovering:
 *
 *   MYSQL GRANTS ARE ADDITIVE ACROSS SCOPES AND CANNOT BE SUBTRACTED.
 *   `GRANT UPDATE ON db.*` followed by `REVOKE UPDATE ON db.audit_entries` is
 *   not narrowing — it is an error, because there is no table-level grant to
 *   revoke, and even where the syntax is accepted the database-level grant
 *   still applies. The only way to withhold UPDATE from one table is to never
 *   grant it at the database level: grant the append-only set broadly, and the
 *   mutating privileges table by table.
 *
 * So this emits, rather than a hand-maintained .sql file that would drift:
 *
 *   SELECT, INSERT       on the whole schema      — every table needs both
 *   UPDATE               per mutable table        — everything but the ledgers
 *   DELETE               per table that permits it
 *
 * The table list is read from the migrations, and the append-only exceptions
 * from GATE_APPEND_ONLY itself, so the account this produces and the gate that
 * judges it cannot disagree. Run the output as the schema owner; run the gate
 * afterwards as the application account.
 *
 * Migrations are NOT run by this account. They run as the schema owner, at
 * deploy time only — which is the whole point: SmartPRS 2's application account
 * IS the schema owner, and ~49 tables exist there that no migration created.
 */
declare(strict_types=1);

require_once __DIR__ . '/../gates/checks/db-privilege.php';
require_once __DIR__ . '/../../tests/lib/laravel_schema_stub.php';

$database = (string) ($_SERVER['argv'][1] ?? 'smartprs3');
$account = (string) ($_SERVER['argv'][2] ?? 'smartprs3_app');
$host = (string) ($_SERVER['argv'][3] ?? 'localhost');

Illuminate\Support\Facades\Schema::reset();

$files = glob(__DIR__ . '/../../database/migrations/*.php');
sort($files);

foreach ($files as $file) {
    (require $file)->up();
}

$tables = [];

foreach (Illuminate\Support\Facades\Schema::$statements as $statement) {
    if (preg_match('/CREATE TABLE `?([a-z0-9_]+)`?/i', $statement, $m)) {
        $tables[$m[1]] = true;
    }
}

$tables = array_keys($tables);
sort($tables);

$who = "'{$account}'@'{$host}'";

echo "-- SmartPRS 3 application account. Generated by tools/db/grants.php --\n";
echo "-- Run as the schema owner, AFTER the migrations: a table-level grant\n";
echo "-- names a table, so the table has to exist. The account below can never\n";
echo "-- change the schema, which is why it cannot have run them itself.\n\n";
echo "CREATE USER IF NOT EXISTS {$who} IDENTIFIED BY '<password>';\n";
echo "REVOKE ALL PRIVILEGES, GRANT OPTION FROM {$who};\n\n";

echo "-- Every table is read and appended to.\n";
echo "GRANT SELECT, INSERT ON `{$database}`.* TO {$who};\n\n";

echo "-- UPDATE and DELETE table by table, because a database-level grant of\n";
echo "-- either cannot be withheld from the append-only tables afterwards.\n";

foreach ($tables as $table) {
    $forbidden = GATE_APPEND_ONLY[$table] ?? [];
    $allowed = array_values(array_diff(['UPDATE', 'DELETE'], $forbidden));

    if ($allowed === []) {
        printf("-- %-28s append-only: SELECT and INSERT only\n", $table);

        continue;
    }

    if ($forbidden !== []) {
        printf("-- %-28s no %s (%s)\n", $table, implode('/', $forbidden), 'append-only in part');
    }

    printf("GRANT %s ON `%s`.`%s` TO %s;\n", implode(', ', $allowed), $database, $table, $who);
}

echo "\nFLUSH PRIVILEGES;\n";
echo "\n-- Then, as the application account:  php tools/gates/gate.php db-privilege\n";
